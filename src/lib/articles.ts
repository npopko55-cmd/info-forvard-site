export type ArticleBlock =
  | { type: "p"; text: string }
  | { type: "h2"; text: string }
  | { type: "ul"; items: string[] }
  | { type: "ol"; items: string[] }
  | { type: "h3"; text: string }
  /** Цитата или пересказ позиции суда/ведомства */
  | { type: "quote"; paragraphs: string[] }
  /** Формула с расшифровкой обозначений */
  | { type: "formula"; formula: string; legend: [string, string][] }
  /** Пример расчёта: условие + строки «показатель — значение» */
  | { type: "example"; title: string; text: string; subtitle: string; rows: [string, string][] }
  /** Чек-лист: пронумерованные группы с пунктами */
  | { type: "checklist"; groups: { title: string; items: string[] }[] }
  /**
   * layout "text" — колонка-подпись + описание, "plain" — две текстовые колонки;
   * по умолчанию — таблица проводок. В ячейке \n делит текст на строки.
   */
  | {
      type: "table";
      head: string[];
      rows: string[][];
      layout?: "text" | "plain";
      caption?: string;
    };

